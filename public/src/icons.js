// Ícone da categoria a partir do nome (não depende mais de emoji no banco)
export function catIcon(name = '') {
  const n = name.toLowerCase();
  if (n.includes('doce')) return 'cake';
  if (n.includes('especia')) return 'star';
  if (n.includes('pizza')) return 'pizza';
  if (n.includes('bebida')) return 'cup';
  if (n.includes('sobremesa')) return 'icecream';
  return 'utensils';
}